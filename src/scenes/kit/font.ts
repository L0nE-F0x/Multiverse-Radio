export interface Glyph {
  w: number;
  bits: Uint8Array; // w*5 cells, 1 = ink
}

const cache = new Map<string, Glyph>();

export function glyph(ch: string): Glyph {
  const key = GLYPHS[ch] !== undefined ? ch : GLYPHS[ch.toUpperCase()] !== undefined ? ch.toUpperCase() : '?';
  let g = cache.get(key);
  if (!g) {
    const rows = GLYPHS[key]!.split('/');
    const w = Math.max(...rows.map((r) => r.length));
    const bits = new Uint8Array(w * 5);
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') bits[y * w + x] = 1;
    });
    g = { w, bits };
    cache.set(key, g);
  }
  return g;
}

export const FONT_HEIGHT = 5;

/** Pixel width of a string at scale 1 (1px letter spacing). */
export function textWidth(text: string, scale = 1): number {
  let w = 0;
  for (const ch of text) w += glyph(ch).w + 1;
  return Math.max(0, w - 1) * scale;
}
