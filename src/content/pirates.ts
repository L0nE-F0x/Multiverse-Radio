// Generated pirate stations: a name, slogan, origin and host for every pirate on the dial.
// Pure and deterministic per seed. Names come from weighted templates with an effective
// vocabulary of roughly thirty thousand (small templates like "Radio Free #place#" are kept
// rare), so a listener browsing a few dozen pirates should never meet the same name twice.
// Slogans, origins and hosts vary independently. The voice pool in content/voice/_pirate.toml gives
// shout-outs to names this grammar can produce (Radio Free Shed, the Midnight Wrong Number,
// the Kitchen Table Broadcasting Company, the Unlicensed Hour).

