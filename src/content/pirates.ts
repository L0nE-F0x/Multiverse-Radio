/**
 * A rule that picks one of several templates by weight; the grammar engine then expands it.
 * Small templates ("Radio Free #place#") get small weights, so no single name turns up often.
 */
export function weighted(options: Readonly<Record<string, number>>): Rule {
  const entries = Object.entries(options);
  const total = entries.reduce((sum, [, w]) => sum + w, 0);
  return (rng) => {
    let r = rng.next() * total;
    for (const [template, w] of entries) {
      r -= w;
      if (r < 0) return template;
    }
    return entries[entries.length - 1]![0];
  };
}

