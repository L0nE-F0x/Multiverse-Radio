/** "3:33:17": a moment inside the minute. */
const stamp: Rule = (rng) => `3:33:${String(rng.int(0, 59)).padStart(2, '0')}`;
/** "3:33:17.204": a more precise moment. The minute never ends, so there are plenty. */
const exact: Rule = (rng) => `3:33:${String(rng.int(0, 59)).padStart(2, '0')}.${String(rng.int(0, 999)).padStart(3, '0')}`;
const fraction: Rule = (rng) => `${rng.int(1, 999)} thousandths`;

