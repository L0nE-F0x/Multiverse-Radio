/** A deadpan remark HUSH appends to a ship-log entry ("Signal smelled faintly of toast."). */
export function shipLogNote(seed: number): string {
  return expandUntil(
    SHIP_LOG_GRAMMAR,
    (attempt) => rngFor(seed, 'shiplog', attempt),
    '#note#',
    (s) => s.length <= SHIP_LOG_NOTE_MAX,
    'Intercept logged.',
  );
}
